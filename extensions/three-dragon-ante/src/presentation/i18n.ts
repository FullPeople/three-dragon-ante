export type WordKey = keyof typeof WORDS;

export function t(key: WordKey | string, lang: Lang, vars?: Record<string, string | number>): string {
  const words = (WORDS as Record<string, Words>)[key];
  let text = words ? words[lang === "zh" ? 0 : 1] : tableText(key, lang);
  if (vars) for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, String(value));
  return text;
}
