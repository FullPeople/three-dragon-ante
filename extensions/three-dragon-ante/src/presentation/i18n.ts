export const cardHint = (value: Card, lang: Lang) => ruleCardHint(value.family, lang);
export const prompt = (code: string, lang: Lang) => rulePrompt(code, lang);
export const alignmentWord = (value: Card, lang: Lang) => ({ good: ["善良", "Good"], evil: ["邪恶", "Evil"], mortal: ["凡人", "Mortal"] } as const)[value.alignment][lang === "zh" ? 0 : 1];
